import { decodeXML } from 'entities';

import { ideviceLines } from './text.js';
import { ElpxError, readZip } from './zip.js';

export interface Idevice {
  id: string;
  type: string;
  lines: string[];
  /** Source the lines come from, to notice changes the text does not show (formatting, settings). */
  raw: string;
}
export interface Block {
  id: string;
  name: string;
  idevices: Idevice[];
}
export interface Page {
  id: string;
  parentId: string;
  title: string;
  depth: number;
  blocks: Block[];
}
export interface Resource {
  size: number;
  crc: number;
}
export interface Project {
  title: string;
  meta: Map<string, string>;
  /** In navigation order (depth first). */
  pages: Page[];
  resources: Map<string, Resource>;
}

interface Node {
  name: string;
  children: Node[];
  text: string;
}

const TOKEN =
  /<!\[CDATA\[([\s\S]*?)\]\]>|<!--[\s\S]*?-->|<\?[\s\S]*?\?>|<![^>]*>|<\/[^>]*>|<([^\s>/]+)(?:"[^"]*"|'[^']*'|[^>"'])*?(\/?)>|([^<]+)/g;

/** Minimal XML reader for content.xml: element names, text and CDATA (attributes are not needed). */
function parseXml(xml: string): Node {
  const root: Node = { name: '', children: [], text: '' };
  const stack = [root];
  for (const m of xml.matchAll(TOKEN)) {
    const top = stack[stack.length - 1]!;
    if (m[1] !== undefined) top.text += m[1];
    else if (m[4] !== undefined) top.text += decodeXML(m[4]);
    else if (m[2] !== undefined) {
      const node: Node = { name: m[2].replace(/^.*:/, ''), children: [], text: '' };
      top.children.push(node);
      if (!m[3]) stack.push(node);
    } else if (m[0].startsWith('</') && stack.length > 1) stack.pop();
  }
  return root;
}

const child = (node: Node | undefined, name: string): Node | undefined => node?.children.find((c) => c.name === name);
const children = (node: Node | undefined, name: string): Node[] => node?.children.filter((c) => c.name === name) ?? [];
const text = (node: Node | undefined, name: string): string => child(node, name)?.text.trim() ?? '';
const keyValues = (node: Node | undefined, item: string): [string, string][] =>
  children(node, item).map((n) => [text(n, 'key'), text(n, 'value')]);

/** Files the author added (everything else in the package is generated by the export). */
const isResource = (name: string): boolean =>
  name.startsWith('content/resources/') || name.startsWith('custom/') || name === 'screenshot.png';
/** Rewritten on every save: they would make every comparison differ. */
const NOISE = new Set(['pp_modified', 'pp_screenshot']);

export async function loadProject(input: Blob | Uint8Array): Promise<Project> {
  const entries = await readZip(input instanceof Blob ? input : new Blob([input as Uint8Array<ArrayBuffer>]));
  const content = entries.get('content.xml');
  if (!content) {
    throw new ElpxError(
      entries.has('contentv3.xml')
        ? 'Legacy .elp project (eXeLearning 2.x): open it in eXeLearning and save it as .elpx first'
        : 'Not an eXeLearning project: content.xml is missing',
    );
  }
  const ode = child(parseXml(new TextDecoder().decode(await content.read())), 'ode');
  if (!ode) throw new ElpxError('content.xml is not an eXeLearning project');

  const meta = new Map<string, string>();
  for (const [key, value] of keyValues(child(ode, 'userPreferences'), 'userPreference')) meta.set(key, value);
  const version = keyValues(child(ode, 'odeResources'), 'odeResource').find(([key]) => key === 'exe_version');
  if (version) meta.set('exe_version', version[1]);
  for (const [key, value] of keyValues(child(ode, 'odeProperties'), 'odeProperty'))
    if (!NOISE.has(key)) meta.set(key, value);

  const flat = children(child(ode, 'odeNavStructures'), 'odeNavStructure').map((nav) => ({
    order: Number(text(nav, 'odeNavStructureOrder')) || 0,
    page: {
      id: text(nav, 'odePageId'),
      parentId: text(nav, 'odeParentPageId'),
      title: text(nav, 'pageName'),
      depth: 0,
      blocks: children(child(nav, 'odePagStructures'), 'odePagStructure')
        .map((block) => ({
          order: Number(text(block, 'odePagStructureOrder')) || 0,
          id: text(block, 'odeBlockId'),
          name: text(block, 'blockName'),
          idevices: children(child(block, 'odeComponents'), 'odeComponent')
            .map((c) => {
              const html = child(c, 'htmlView')?.text ?? '';
              const json = child(c, 'jsonProperties')?.text ?? '';
              return {
                order: Number(text(c, 'odeComponentsOrder')) || 0,
                id: text(c, 'odeIdeviceId'),
                type: text(c, 'odeIdeviceTypeName'),
                lines: ideviceLines(html, json),
                raw: html.trim() || json.trim(),
              };
            })
            .sort((x, y) => x.order - y.order)
            .map(({ order: _order, ...idevice }): Idevice => idevice),
        }))
        .sort((x, y) => x.order - y.order)
        .map(({ order: _order, ...block }): Block => block),
    } as Page,
  }));

  // The XML lists pages flat; the tree comes from the parent ids and the order among siblings.
  const ids = new Set(flat.map((f) => f.page.id));
  const pages: Page[] = [];
  const visit = (parentId: string | undefined, depth: number): void => {
    for (const f of flat
      .filter((x) => (parentId === undefined ? !ids.has(x.page.parentId) : x.page.parentId === parentId))
      .sort((x, y) => x.order - y.order)) {
      if (pages.includes(f.page)) continue; // a cycle or a repeated id
      f.page.depth = depth;
      pages.push(f.page);
      if (f.page.id) visit(f.page.id, depth + 1);
    }
  };
  visit(undefined, 0);

  const resources = new Map<string, Resource>();
  for (const e of entries.values()) if (isResource(e.name)) resources.set(e.name, { size: e.size, crc: e.crc });
  return { title: meta.get('pp_title') ?? '', meta, pages, resources };
}
